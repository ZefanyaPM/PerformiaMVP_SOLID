    private void tampilkanPengumuman(int index) {
        PengumumanDetail detail = pengumumanService.getPengumuman(index);
        labelJudulPengumuman.setText(detail.judul());
        labelIsiPengumuman1.setText(detail.barisIsi().get(0));
        labelIsiPengumuman2.setText(detail.barisIsi().get(1));
        labelIsiPengumuman3.setText(detail.barisIsi().get(2));
        labelIsiPengumuman4.setText(detail.barisIsi().get(3));
    }

