    public void refreshDaftarReviewTugas(){
        model = (DefaultTableModel) tabelDaftarTugas.getModel();
        model.setRowCount(0);
        for (TugasReview review : karyawanService.getTugasMenungguReview()) {
            model.addRow(new Object[]{
                review.namaKaryawan(),
                review.judulTugas(),
                review.tanggalSubmit(),
                review.status()
            });
        }
    }

