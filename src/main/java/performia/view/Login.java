    private void bLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bLoginActionPerformed
        String inputEmail = textEmail.getText();
        String inputPassword = textPassword.getText();

        int manajerIndex = authService.cariManajerIndex(inputEmail, inputPassword);
        if (manajerIndex != -1) {
            JOptionPane.showMessageDialog(this, "Berhasil login sebagai Manajer!");
            MainFrame_GUI_Manajer guiManajer = new MainFrame_GUI_Manajer(manajerIndex);
            guiManajer.setVisible(true);
            this.dispose();
            return;
        }

        int karyawanIndex = authService.cariKaryawanIndex(inputEmail, inputPassword);
        if (karyawanIndex != -1) {
            JOptionPane.showMessageDialog(this, "Berhasil login sebagai Karyawan!");
            MainFrame_GUI_Karyawan guiKaryawan = new MainFrame_GUI_Karyawan(karyawanIndex);
            guiKaryawan.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Email atau password salah");
        }
           
    }//GEN-LAST:event_bLoginActionPerformed

